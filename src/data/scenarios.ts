import type { Scenario, CodeLine } from '../types';

// Helper to tokenize code easily
function line(lineNumber: number, rawText: string, description?: string): CodeLine {
  // Simple token parser for syntax highlighting
  const tokens = parseTokens(rawText);
  return { lineNumber, tokens, rawText, description };
}

function parseTokens(text: string) {
  const result: { text: string; type: any }[] = [];
  let remaining = text;

  const patterns: [RegExp, any][] = [
    [/^(\/\/[^\n]*)/, 'comment'],
    [/^("(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'|`(?:[^`\\]|\\.)*`)/, 'string'],
    [/^(const|let|var|function|return|while|if|else|async|await|new|class|for)\b/, 'keyword'],
    [/^(console\.log|setTimeout|Promise\.resolve|Date\.now|fetch|queueMicrotask|bakePizza|prepareDough|resolve)\b/, 'function'],
    [/^\b(\d+)\b/, 'number'],
    [/^(=>|===|==|<=|>=|<|>|\+|\-|\*|\/|=)/, 'operator'],
    [/^([(){}\[\];,.:])/, 'punctuation'],
    [/^([a-zA-Z_$][a-zA-Z0-9_$]*)/, 'variable'],
    [/^(\s+)/, 'plain'],
  ];

  while (remaining.length > 0) {
    let matched = false;
    for (const [regex, type] of patterns) {
      const match = remaining.match(regex);
      if (match) {
        result.push({ text: match[0], type });
        remaining = remaining.slice(match[0].length);
        matched = true;
        break;
      }
    }
    if (!matched) {
      result.push({ text: remaining[0], type: 'plain' });
      remaining = remaining.slice(1);
    }
  }

  return result;
}

